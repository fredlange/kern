"""Differential test on kern/fuzz.py's programs: every generated loop/handler program and every
template mutant, compiled to Rust, against kern/run.py (extends scorecard C2 beyond the examples).

    python runtime/fuzzdiff.py [--seed 1] [--loops 300] [--handlers 200] [--no-mutants] [--per-def 100]

All programs go into one crate (one module each, picked by the first argument), so there is one
cargo build. run.py gets kern/fuzz.py's spec-respecting provider; the binary replays its values.
"""
import argparse
import os
import random
import subprocess
import sys
import tempfile
import time

RUNTIME = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(RUNTIME)
sys.path.insert(0, ROOT)
sys.path.insert(0, RUNTIME)

import difftest  # noqa: E402
import emit_rust  # noqa: E402
from kern import fuzz  # noqa: E402
from kern.syntax import parse_module  # noqa: E402
from kern.wf import check_module  # noqa: E402


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--loops", type=int, default=300)
    ap.add_argument("--handlers", type=int, default=200)
    ap.add_argument("--no-mutants", action="store_true")
    ap.add_argument("--per-def", type=int, default=100)
    a = ap.parse_args(argv)
    t0 = time.time()
    progs, not_wf, unsupported = [], 0, {}
    for label, src, mod, seed, _ in fuzz.jobs(a.seed, a.loops, a.handlers, 0, not a.no_mutants):
        try:
            defs = mod if mod is not None else check_module(parse_module(src))
        except Exception:
            not_wf += 1
            continue
        name = f"p{len(progs)}"
        try:
            rust = emit_rust.Gen(defs, name).module()
        except emit_rust.Unsupported as e:
            unsupported[label] = str(e)
            continue
        progs.append((label, name, defs, seed, rust))

    crate = os.path.join(RUNTIME, "build", "fuzzdiff")
    os.makedirs(os.path.join(crate, "src"), exist_ok=True)
    for _, name, _, _, rust in progs:
        p = os.path.join(crate, "src", f"{name}.rs")
        if not os.path.exists(p) or open(p).read() != rust:
            open(p, "w").write(rust)
    arms = "\n".join(f'        "{n}" => kern_rt::driver::main_with::<{n}::M>(a),' for _, n, _, _, _ in progs)
    main_rs = ("// GENERATED by runtime/fuzzdiff.py\n" + "".join(f"mod {n};\n" for _, n, _, _, _ in progs)
               + "\nfn main() {\n    let mut a: Vec<String> = std::env::args().collect();\n    let which = a.remove(1);\n"
               + "    match which.as_str() {\n" + arms + "\n        other => panic!(\"no module {other}\"),\n    }\n}\n")
    open(os.path.join(crate, "src", "main.rs"), "w").write(main_rs)
    open(os.path.join(crate, "Cargo.toml"), "w").write(f"""# GENERATED by runtime/fuzzdiff.py
[package]
name = "fuzzdiff"
version = "0.1.0"
edition = "2021"

[dependencies]
kern-rt = {{ path = "{os.path.join(RUNTIME, 'kern-rt')}" }}

[profile.release]
opt-level = 1

[workspace]
""")
    t_gen = time.time() - t0
    t0 = time.time()
    binary = emit_rust.build(crate)
    t_build = time.time() - t0

    t0 = time.time()
    calls = div_total = 0
    bad = []
    for label, name, defs, seed, _ in progs:
        rnd = random.Random(seed)
        case, _ = difftest.build_case(defs, rnd, a.per_def, seed, provider=fuzz._provider(defs, random.Random(seed)))
        with tempfile.NamedTemporaryFile("w", suffix=".script", delete=False) as f:
            f.write("\n".join(case.script) + "\n")
        r = subprocess.run([binary, name, "run", f.name], capture_output=True, text=True)
        os.unlink(f.name)
        got = r.stdout.splitlines() if r.returncode == 0 else [f"<crash {r.stderr[-300:]}>"]
        div = [i for i in range(max(len(got), len(case.expected)))
               if i >= len(got) or i >= len(case.expected) or got[i] != case.expected[i]]
        calls += sum(1 for s in case.script if s.startswith("call "))
        div_total += len(div)
        if div:
            i = div[0]
            bad.append((label, len(div), case.where[i] if i < len(case.where) else "?",
                        case.expected[i] if i < len(case.expected) else "<none>", got[i] if i < len(got) else "<none>"))
    t_run = time.time() - t0
    print(f"programs: {len(progs)} compiled, {not_wf} not well-formed (skipped), {len(unsupported)} unsupported")
    for label, why in list(unsupported.items())[:5]:
        print(f"   UNSUPPORTED {label}: {why}")
    print(f"calls: {calls}, divergences: {div_total} in {len(bad)} programs "
          f"(generate {t_gen:.0f}s, cargo {t_build:.0f}s, run {t_run:.0f}s)")
    for label, n, where, want, got in bad[:8]:
        print(f"   DIV {label} ({n} lines): {where}\n        run.py: {want}\n        binary: {got}")
    return 0 if div_total == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
