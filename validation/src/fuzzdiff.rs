//! Differential test on the fuzzer's programs (port of validation/fuzzdiff.py): every generated loop and handler
//! program and every template mutant, compiled to Rust, against the interpreter. Extends scorecard C2 of
//! docs/research/RUNTIME_PLAN.md beyond the examples.
//!
//! ```text
//! fuzzdiff [--seed 1] [--loops 300] [--handlers 200] [--no-mutants] [--per-def 100]
//! ```
//!
//! All programs go into one crate (one module each, picked by the binary's first argument), so there is one cargo
//! build. The interpreter gets the fuzzer's spec-respecting provider; the binary replays its values.

use std::cell::RefCell;
use std::rc::Rc;

use kern::emit_rust::{build, build_dir, runtime_dir, Gen};
use kern::pyrandom::Random;
use kern::syntax::{parse_module, Module};
use kern::wf::check_module;

use crate::difftest::{build_case, ROOT};
use crate::fuzz::{jobs, provider};

pub struct Summary {
    pub compiled: usize,
    pub not_wf: usize,
    pub unsupported: Vec<(String, String)>,
    pub calls: usize,
    pub divergences: usize,
    /// (label, divergent lines, where, interpreter, binary) for the first divergence of each program
    pub bad: Vec<(String, usize, String, String, String)>,
}

pub fn run(seed: i128, loops: usize, handlers: usize, mutants: bool, per_def: usize) -> Result<Summary, String> {
    let mut progs: Vec<(String, String, Module, i128, String)> = vec![];
    let (mut not_wf, mut unsupported) = (0, vec![]);
    for job in jobs(std::path::Path::new(ROOT), seed, loops, handlers, 0, mutants) {
        let defs = match (&job.module, &job.src) {
            (Some(m), _) => m.clone(),
            (None, Some(src)) => match parse_module(src, true).ok().filter(|m| check_module(m).is_ok()) {
                Some(m) => m,
                None => {
                    not_wf += 1;
                    continue;
                }
            },
            (None, None) => continue,
        };
        let name = format!("p{}", progs.len());
        match Gen::new(&defs, &name).module() {
            Ok(rust) => progs.push((job.label, name, defs, job.seed, rust)),
            Err(e) => unsupported.push((job.label, e.0)),
        }
    }

    let crate_dir = format!("{}/fuzzdiff", build_dir());
    std::fs::create_dir_all(format!("{crate_dir}/src")).map_err(|e| e.to_string())?;
    let write = |p: String, text: &str| -> Result<(), String> {
        // unchanged files keep their mtime: cargo rebuilds less
        if std::fs::read_to_string(&p).ok().as_deref() != Some(text) {
            std::fs::write(&p, text).map_err(|e| format!("{p}: {e}"))?;
        }
        Ok(())
    };
    for (_, name, _, _, rust) in &progs {
        write(format!("{crate_dir}/src/{name}.rs"), rust)?;
    }
    let mut main_rs = String::from("// GENERATED by validation/src/fuzzdiff.rs\n");
    for (_, n, _, _, _) in &progs {
        main_rs.push_str(&format!("mod {n};\n"));
    }
    main_rs.push_str("\nfn main() {\n    let mut a: Vec<String> = std::env::args().collect();\n    let which = a.remove(1);\n    match which.as_str() {\n");
    for (_, n, _, _, _) in &progs {
        main_rs.push_str(&format!("        \"{n}\" => kern_rt::driver::main_with::<{n}::M>(a),\n"));
    }
    main_rs.push_str("        other => panic!(\"no module {other}\"),\n    }\n}\n");
    write(format!("{crate_dir}/src/main.rs"), &main_rs)?;
    let runtime = runtime_dir().map_err(|e| e.to_string())?;
    write(
        format!("{crate_dir}/Cargo.toml"),
        &format!(
            "# GENERATED by validation/src/fuzzdiff.rs\n[package]\nname = \"fuzzdiff\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n\
             [dependencies]\nkern-rt = {{ path = \"{runtime}\" }}\n\n[profile.release]\nopt-level = 1\n\n[workspace]\n"
        ),
    )?;
    let binary = build(&crate_dir).map_err(|e| e.to_string())?;

    let (mut calls, mut divergences, mut bad) = (0, 0, vec![]);
    for (label, name, defs, seed, _) in &progs {
        let mut rng = Random::from_int(*seed);
        let prov = provider(defs, Rc::new(RefCell::new(Random::from_int(*seed))));
        let (case, _) = build_case(defs, &mut rng, per_def, *seed, Some(prov))?;
        let script = std::env::temp_dir().join(format!("kern-fuzzdiff-{}-{name}.script", std::process::id()));
        std::fs::write(&script, case.script.join("\n") + "\n").map_err(|e| e.to_string())?;
        let r = std::process::Command::new(&binary).arg(name).arg("run").arg(&script).output().map_err(|e| e.to_string())?;
        let _ = std::fs::remove_file(&script);
        let got: Vec<String> = if r.status.success() {
            String::from_utf8_lossy(&r.stdout).lines().map(String::from).collect()
        } else {
            let err = String::from_utf8_lossy(&r.stderr);
            vec![format!("<crash {}>", &err[err.len().saturating_sub(300)..])]
        };
        let n = got.len().max(case.expected.len());
        let div: Vec<usize> = (0..n).filter(|&i| i >= got.len() || i >= case.expected.len() || got[i] != case.expected[i]).collect();
        calls += case.script.iter().filter(|s| s.starts_with("call ")).count();
        divergences += div.len();
        if let Some(&i) = div.first() {
            bad.push((
                label.clone(),
                div.len(),
                case.place.get(i).cloned().unwrap_or("?".into()),
                case.expected.get(i).cloned().unwrap_or("<none>".into()),
                got.get(i).cloned().unwrap_or("<none>".into()),
            ));
        }
    }
    Ok(Summary { compiled: progs.len(), not_wf, unsupported, calls, divergences, bad })
}

pub fn main(argv: &[String]) -> i32 {
    let (mut seed, mut loops, mut handlers, mut mutants, mut per_def) = (1i128, 300usize, 200usize, true, 100usize);
    let mut i = 0;
    while i < argv.len() {
        let flag = argv[i].as_str();
        let val = |i: &mut usize| {
            *i += 1;
            argv.get(*i).and_then(|v| v.parse::<i128>().ok()).unwrap_or_else(|| panic!("{flag} needs a number"))
        };
        match flag {
            "--seed" => seed = val(&mut i),
            "--loops" => loops = val(&mut i) as usize,
            "--handlers" => handlers = val(&mut i) as usize,
            "--per-def" => per_def = val(&mut i) as usize,
            "--no-mutants" => mutants = false,
            other => {
                eprintln!("fuzzdiff: unknown argument {other}");
                return 2;
            }
        }
        i += 1;
    }
    let t0 = std::time::Instant::now();
    let s = match run(seed, loops, handlers, mutants, per_def) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("fuzzdiff: {e}");
            return 1;
        }
    };
    println!("programs: {} compiled, {} not well-formed (skipped), {} unsupported", s.compiled, s.not_wf, s.unsupported.len());
    for (label, why) in s.unsupported.iter().take(5) {
        println!("   UNSUPPORTED {label}: {why}");
    }
    println!("calls: {}, divergences: {} in {} programs ({:.0}s)", s.calls, s.divergences, s.bad.len(), t0.elapsed().as_secs_f64());
    for (label, n, place, want, got) in s.bad.iter().take(8) {
        println!("   DIV {label} ({n} lines): {place}\n        interpreter: {want}\n        binary:      {got}");
    }
    if s.divergences == 0 {
        0
    } else {
        1
    }
}
